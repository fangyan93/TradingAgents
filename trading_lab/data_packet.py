"""Point-in-time QQQ/TQQQ packet creation using TradingAgents' data layer."""

from __future__ import annotations

from datetime import date
from pathlib import Path
from typing import Any

import pandas as pd
from stockstats import wrap

from tradingagents.dataflows.config import set_config
from tradingagents.dataflows.stockstats_utils import load_ohlcv
from tradingagents.default_config import DEFAULT_CONFIG


class MarketDataUnavailableError(RuntimeError):
    """Raised when the upstream data layer cannot provide usable price data."""


def _number(value: Any) -> float | None:
    if value is None or pd.isna(value):
        return None
    return round(float(value), 4)


def _discard_malformed_cache(symbol: str, cache_dir: Path) -> None:
    """Remove only cache files the upstream loader itself cannot read.

    A failed yfinance download can leave a header-only CSV without ``Date``.
    ``load_ohlcv`` expects that column on every cached file, so retaining it
    prevents a later successful network retry. These files are generated by
    this wrapper under its ignored local cache directory.
    """
    for candidate in cache_dir.glob(f"{symbol}-YFin-data-*.csv"):
        try:
            columns = pd.read_csv(candidate, nrows=0).columns
        except (OSError, pd.errors.ParserError):
            columns = []
        if "Date" not in columns:
            candidate.unlink(missing_ok=True)


def _instrument_snapshot(symbol: str, as_of: str) -> dict[str, Any]:
    try:
        data = load_ohlcv(symbol, as_of)
    except (KeyError, OSError, pd.errors.ParserError) as exc:
        raise MarketDataUnavailableError(
            f"Could not load usable Yahoo Finance OHLCV data for {symbol} on or before {as_of}. "
            "Check the network connection and retry."
        ) from exc
    if data.empty:
        raise MarketDataUnavailableError(f"No OHLCV data was available for {symbol} on or before {as_of}.")

    enriched = wrap(data.copy())
    for column in ("close_20_sma", "close_50_sma", "close_200_sma", "rsi", "macd", "macds", "atr"):
        enriched[column]
    latest = enriched.iloc[-1]
    closes = enriched["close"].astype(float)

    def percent_return(days: int) -> float | None:
        if len(closes) <= days:
            return None
        return round((closes.iloc[-1] / closes.iloc[-days - 1] - 1) * 100, 3)

    recent = data.tail(10).copy()
    recent["Date"] = pd.to_datetime(recent["Date"]).dt.strftime("%Y-%m-%d")
    return {
        "symbol": symbol,
        "last_trading_date": str(pd.to_datetime(latest["Date"]).date()),
        "last_close": _number(latest["close"]),
        "indicators": {
            "sma_20": _number(latest["close_20_sma"]),
            "sma_50": _number(latest["close_50_sma"]),
            "sma_200": _number(latest["close_200_sma"]),
            "rsi_14": _number(latest["rsi"]),
            "macd": _number(latest["macd"]),
            "macd_signal": _number(latest["macds"]),
            "atr": _number(latest["atr"]),
        },
        "returns_percent": {"one_day": percent_return(1), "five_day": percent_return(5), "twenty_day": percent_return(20)},
        "recent_ohlcv": [
            {
                "date": row["Date"],
                "open": _number(row.get("Open")),
                "high": _number(row.get("High")),
                "low": _number(row.get("Low")),
                "close": _number(row.get("Close")),
                "volume": _number(row.get("Volume")),
            }
            for _, row in recent.iterrows()
        ],
    }


def collect_packet(*, as_of: str, cache_dir: Path) -> dict[str, Any]:
    """Collect only data available at ``as_of`` and return a compact packet."""
    selected_date = date.fromisoformat(as_of).isoformat()
    config = DEFAULT_CONFIG.copy()
    config["data_cache_dir"] = str(cache_dir)
    set_config(config)
    cache_dir.mkdir(parents=True, exist_ok=True)
    for symbol in ("QQQ", "TQQQ"):
        _discard_malformed_cache(symbol, cache_dir)

    return {
        "as_of": selected_date,
        "data_source": "Yahoo Finance via TradingAgents dataflows",
        "scope": {
            "market_signal": "QQQ",
            "research_instrument": "TQQQ",
            "note": "Research only. This packet is not an order instruction or a portfolio allocation recommendation.",
        },
        "instruments": [_instrument_snapshot("QQQ", selected_date), _instrument_snapshot("TQQQ", selected_date)],
    }
